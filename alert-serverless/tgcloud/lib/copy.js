export function statusLocale(locale = STATUS_LOCALE) {
  return Object.hasOwn(STATUS_COPY, locale) ? locale : 'en';
}

export function statusText(locale, key, values = {}) {
  const text = STATUS_COPY[statusLocale(locale)][key];
  if (text === undefined) throw new Error(`Missing status translation: ${key}`);
  return text.replace(/\{([a-zA-Z]+)\}/g, (_match, name) => String(values[name] ?? ''));
}
